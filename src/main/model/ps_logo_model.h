/*
 * PS1 logo model - converted from a user-supplied GLB (a Sketchfab-sourced,
 * FBX-derived model this time - "Logo" node, 4 sub-meshes/materials -
 * rather than the earlier flat Grease Pencil sketch). This one has genuine
 * geometric depth (its own bounding box is ~57 units deep vs ~692 wide -
 * a real relief, not a ~0.46-unit-thick flat cutout like the model this
 * replaces), and its parent nodes carry correction quaternions (the
 * original FBX was Z-up; Sketchfab's own export pipeline rotates it to
 * Y-up) which were walked and applied when extracting vertex positions, so
 * these coordinates are already in corrected Y-up space - matching what a
 * standard Y-up viewer would show.
 *
 * Because this model's own bounding box already reads as tall in Y (534
 * units) and thin in Z (57 units) - i.e. already standing upright with its
 * face toward the camera - it likely does NOT need the 90-degree stand-up
 * tilt the previous (flat, Y-thin) model required. That's a reasoned best
 * guess from the geometry, not a rendered confirmation, so drawXMBBackground
 * ships a few alternate-tilt "TEST logo" theme variants alongside the main
 * one specifically so this can be confirmed/corrected by eye rather than by
 * guessing blind - see xmb_bg.c's drawTestLogoTheme()/drawPSLogoModel().
 *
 * Colours are the 4 materials' baseColorFactor values, gamma-corrected
 * (2.2) from glTF's linear colour space so they read at normal on-screen
 * brightness: red, yellow, teal, blue.
 *
 * Model is centred on its own bounding-box centre and scaled 0.5x from the
 * source GLB's units.
 */

