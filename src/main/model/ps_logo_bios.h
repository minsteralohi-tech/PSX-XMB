/*
 * PlayStation logo, converted from assets/playstation_logo.glb by
 * tools/glb2pslogo.py. Generated - do not hand-edit.
 *
 * This is NOT the model in ps_logo_model.h. That one is an older, coarser
 * conversion still used by the TEST logo theme and PS4 v2; this one is the
 * real logo and is what the boot sequence draws.
 *
 * The source GLB has four sub-meshes, one per material, split along the
 * swoosh depth: the upright P plus three slabs. Its root node carries a
 * Y/Z-flipping correction matrix (Sketchfab exports Z-up FBX to Y-up),
 * which is applied here, and Y is then negated because PS1 screen space
 * counts downward.
 *
 * TWO THINGS ARE BAKED IN, both deliberately:
 *
 *   1. The resting pose - the BIOS screen's three-quarter view. Vertices
 *      come out already rotated, so drawing at yaw 0 gives the finished
 *      orientation and the intro only has to animate one angle back to
 *      zero. Getting the pose from three runtime angles instead would mean
 *      depending on cosmosRotate()'s axis naming, which does not match its
 *      parameter names (its "yaw" turns about Z, its "roll" about X).
 *
 *   2. Reversed winding. The offline check that picked this pose culls a
 *      face when the screen-space cross product is negative; GTE_CMD_NCLIP,
 *      which computes the same quantity, is used the other way round -
 *      faces are kept when MAC0 > 0. Vertices 1 and 2 are swapped on export
 *      so the two agree.
 *
 * Colours are the flat PlayStation palette rather than the GLB's
 * baseColorFactors, which are linear and read far too bright converted
 * naively. Material 1 is blue and material 3 yellow, not the other way
 * round: the near slab is the yellow end of the swoosh.
 */

